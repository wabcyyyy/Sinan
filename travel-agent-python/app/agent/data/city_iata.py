def resolve_iata(city: str | None) -> str | None:
    """城市名 → IATA 代码；未命中返回 None（**不猜、不兜底**）。

    调用方（航班工具）必须把 None 当作"这段缺席"如实上报，而不是换一个
    近似城市去查——映射错机场比查不到更糟。
    """
    name = str(city or "").strip()
    if not name:
        return None
    hit = _CITY_IATA.get(name)
    if hit:
        return hit
    # 常见写法归一：去掉"市"后缀（"上海市"→"上海"）；仍不命中即缺席
    if name.endswith("市"):
        return _CITY_IATA.get(name[:-1])
    return None


def known_cities() -> tuple[str, ...]:
    """已覆盖城市（审计/文档用）。"""
    return tuple(_CITY_IATA)
